const echapper = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Les mots du glossaire, du plus long au plus court (« chaux hydraulique » avant « chaux »). */
const MOTS = Object.keys(GLOSSAIRE).sort((a, b) => b.length - a.length);
export const RE_GLOSSAIRE = new RegExp(`(?<![\\p{L}\\p{N}-])(${MOTS.map(echapper).join('|')})(?![\\p{L}\\p{N}-])`, 'giu');

export const definitionGlossaire = (mot: string) => {
  const cle = MOTS.find((m) => m.toLowerCase() === mot.toLowerCase());
  return cle ? GLOSSAIRE[cle] : undefined;
};
